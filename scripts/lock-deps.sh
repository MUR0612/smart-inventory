#!/usr/bin/env bash
# Regenerate requirements.lock.txt (full pinned dependency tree) for each image,
# resolved inside the same base image the Dockerfiles use.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
IMAGE="python:3.12-slim-trixie"
for dir in inventory-service order-service db; do
  docker run --rm -v "$ROOT/$dir:/work" -w /work "$IMAGE" sh -c \
    'pip install -q --disable-pip-version-check --root-user-action=ignore -r requirements.txt && pip freeze --exclude pip > requirements.lock.txt.tmp'
  { echo "# Generated by scripts/lock-deps.sh from requirements.txt - do not edit by hand."; cat "$ROOT/$dir/requirements.lock.txt.tmp"; } > "$ROOT/$dir/requirements.lock.txt"
  rm "$ROOT/$dir/requirements.lock.txt.tmp"
  echo "locked $dir"
done
